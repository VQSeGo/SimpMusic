baselineProfile {
    // One profile for every variant: androidApp/src/main/generated/baselineProfiles/baseline-prof.txt
    // (committed). Regenerated by hand with a phone attached, never as part of a normal build.
    mergeIntoMain = true
    saveInSrc = true
    automaticGenerationDuringBuild = false
}

// The baselineprofile plugin adds nonMinifiedRelease (profile generation) and benchmarkRelease
// (Macrobenchmark). Both get the package id com.maxrave.simpmusic.bp (`targetAppId` in
// baselineprofile/build.gradle.kts) so they install next to the real app instead of over it, and the debug key so
// the instrumentation can install them at all. The profile's rules are class names; the package id
// does not change the result.
androidComponents {
    onVariants(selector().withBuildType("nonMinifiedRelease")) {
        it.applicationId.set("com.maxrave.simpmusic.bp")
        it.signingConfig.setConfig(android.signingConfigs.getByName("debug"))
    }
    onVariants(selector().withBuildType("benchmarkRelease")) {
        it.applicationId.set("com.maxrave.simpmusic.bp")
        it.signingConfig.setConfig(android.signingConfigs.getByName("debug"))
    }
}

